with norm as (
  select id, codice, split_part(codice, '/', 1) as famiglia,
         upper(regexp_replace(codice, '[^A-Za-z0-9,]', '', 'g')) as chiave
  from articoli
), sul_sito as (
  select n.* from norm n
  join sito s on upper(regexp_replace(s.codice, '[^A-Za-z0-9,]', '', 'g')) = n.chiave
), famiglie as (
  select distinct upper(regexp_replace(famiglia, '[^A-Za-z0-9,]', '', 'g')) as fam from sul_sito
  where famiglia not ilike 'G07663%'
  union   -- anche i codici del sito che nel gestionale esistono solo con lo slash (es. B1126 -> B1126/1)
  select distinct upper(regexp_replace(split_part(codice, '/', 1), '[^A-Za-z0-9,]', '', 'g')) from sito
  where codice not ilike 'G07663%'
), nostri as (
  select id from norm where codice not like '%/%'
  union select id from sul_sito where codice not ilike 'G07663%'
  union select n.id from norm n join famiglie f on upper(regexp_replace(n.famiglia, '[^A-Za-z0-9,]', '', 'g')) = f.fam
  union select id from norm where codice ilike 'A0110/%' or codice ilike 'A0210/%'   -- calici e patene in ceramica
)
update articoli set fornitore_id = (select id from fornitori where codice = 'PROPRIA'), modificato_il = now()
where id in (select id from nostri);

with a as (
  select id, substring(split_part(codice, '/', 1) from '(\d+)$') as cifre
  from articoli where fornitore_id is null and codice like '%/%'
    and codice not ilike 'R029/%'   -- icone e trittici: Mollica o San Paolo? da decidere, restano senza
), b as (
  select id, ltrim(substr(cifre, 3), '0') as n from a where length(cifre) >= 3
)
update articoli set fornitore_id = f.id, modificato_il = now()
from b join fornitori f on ltrim(f.codice, '0') = b.n
where articoli.id = b.id and b.n <> '';

-- Controllo: quanti articoli per fornitore (la riga vuota = ancora senza fornitore)
select f.codice, f.ragione_sociale, count(*) as articoli,
       min(a.codice || ' – ' || a.descrizione) as esempio_1, max(a.codice || ' – ' || a.descrizione) as esempio_2
from articoli a left join fornitori f on f.id = a.fornitore_id
group by 1, 2
order by articoli desc;
